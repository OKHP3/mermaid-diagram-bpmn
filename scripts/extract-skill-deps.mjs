#!/usr/bin/env node
/**
 * Extract `depends_on` from all BP-SKILL SKILL.md files and emit a typed
 * TypeScript constant consumed by DependencyFlowDiagram.tsx and the static
 * Mermaid export.
 *
 * Usage (from workspace root):
 *   node scripts/extract-skill-deps.mjs
 *
 * Output:
 *   app/src/data/skill-deps-auto.ts
 */

import fs from "fs";
import os from "os";
import path from "path";
import { fileURLToPath } from "url";
import { parseSkillFrontmatter, getSkillField } from "./skill-frontmatter.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const SKILLS_DIR = path.join(ROOT, "skills");
const COMMITTED_OUT = process.env.SKILL_DEPS_COMMITTED_OVERRIDE
  ? path.resolve(process.env.SKILL_DEPS_COMMITTED_OVERRIDE)
  : path.join(ROOT, "app/src/data/skill-deps-auto.ts");

const CHECK_MODE = process.argv.includes("--check");
const OUT = CHECK_MODE
  ? path.join(os.tmpdir(), "skill-deps-check.ts")
  : COMMITTED_OUT;

const BP_SKILL_IDS = [
  "okhp3-process-intake-and-scope",
  "okhp3-stakeholder-and-role-mapping",
  "okhp3-elicitation-interviews",
  "okhp3-as-is-process-capture",
  "okhp3-process-narrative-authoring",
  "okhp3-visual-process-modeling",
  "okhp3-process-gap-exception-analysis",
  "okhp3-future-state-change-strategy",
  "okhp3-decision-model-authoring",
  "okhp3-process-validation-scoring",
  "okhp3-process-measures-controls",
  "okhp3-sop-work-instructions",
  "okhp3-raci-governance-matrix",
  "okhp3-sipoc-generation",
  "okhp3-publication-handoff-packaging",
];

function extractDeps(skillId) {
  const file = path.join(SKILLS_DIR, skillId, "SKILL.md");
  const content = fs.readFileSync(file, "utf8");
  const frontmatter = parseSkillFrontmatter(content);
  const raw = getSkillField(frontmatter, "depends_on");
  if (!raw || raw === "[]") return [];
  return raw
    .split(/[;,]/)
    .map((item) => item.trim().replace(/^[\"']|[\"']$/g, ""))
    .filter((item) => /^[a-z][a-z0-9-]*$/.test(item));
}

const deps = {};
for (const id of BP_SKILL_IDS) {
  deps[id] = extractDeps(id);
}

const lines = [
  "// AUTO-GENERATED by scripts/extract-skill-deps.mjs — do not edit manually.",
  "// Source: skills/*/SKILL.md frontmatter (depends_on field).",
  "// Re-run:  node scripts/extract-skill-deps.mjs",
  "",
  "export const SKILL_DEPS: Record<string, readonly string[]> = {",
  ...Object.entries(deps).map(
    ([id, d]) => `  "${id}": ${JSON.stringify(d)},`,
  ),
  "};",
  "",
];

fs.writeFileSync(OUT, lines.join("\n"), "utf8");

if (CHECK_MODE) {
  const generated = fs.readFileSync(OUT, "utf8");
  const committed = fs.readFileSync(COMMITTED_OUT, "utf8");
  if (generated !== committed) {
    console.error(
      "[extract-skill-deps] FAIL: skill-deps-auto.ts is stale — run node scripts/extract-skill-deps.mjs",
    );
    process.exit(1);
  }
  console.log("[extract-skill-deps] OK: skill-deps-auto.ts is up to date.");
} else {
  console.log(`[extract-skill-deps] Generated ${path.relative(ROOT, OUT)}`);
  for (const [id, d] of Object.entries(deps)) {
    if (d.length > 0) console.log(`  ${id} -> [${d.join(", ")}]`);
  }
}
